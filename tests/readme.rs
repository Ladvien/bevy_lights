//! **The README's example is compiled, not just read.**
//!
//! The quick-start snippet is the first code anyone runs, so a field added to a component and not to the
//! README costs every new user three compile errors before they have used the crate at all. It did,
//! once: `FlameSite` gained `kindle` in one iteration and the snippet was not updated for four. This test
//! extracts the `Quick start` block, writes it into a scratch crate that depends on this one **by path**,
//! and builds it. A snippet that does not compile fails CI.
//!
//! The build is slow (Bevy is a dependency of the scratch crate), so it runs once and its result is
//! reused by the assertions. The scratch crate lives under the target directory, never in the tree.

// Tests are allowed to panic: a failed assertion and a missing fixture are the same thing here, and
// `AGENTS.md`'s no-`unwrap`/`expect`/`panic!` rule is about library code.
#![allow(clippy::expect_used, clippy::unwrap_used, clippy::panic)]

use std::path::PathBuf;
use std::process::Command;

/// The rust source of the README's `## Quick start` block.
fn quick_start() -> String {
    let readme = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("README.md");
    let text = std::fs::read_to_string(&readme).expect("the crate ships its README");
    let after = text.split_once("## Quick start").expect("the README has a Quick start section").1;
    let body = after.split_once("```rust").expect("the section opens a rust block").1;
    let source = body.split_once("```").expect("and closes it").0;
    assert!(source.contains("fn main"), "the block is a program, not a fragment: {source}");
    source.to_string()
}

/// The README's program, written into this crate's own `examples/` so it compiles against the same lockfile
/// and dependency graph — a separate crate would have to resolve Bevy from scratch, which needs the network.
///
/// `README_EXAMPLE` is declared in `Cargo.toml` behind a feature of the same name that nothing enables, so
/// `cargo build --examples` never builds it and the published package never ships it.
fn write_example(source: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let path = dir.join("examples/readme_quick_start.rs");
    // A header rather than the bare snippet: the crate lints `missing_docs`, so an example with no module
    // doc fails the build for a reason that has nothing to do with the README being stale.
    let program = format!(
        "//! The README's quick start, generated by `tests/readme.rs` and compiled by it. Do not edit.\n\n{source}"
    );
    std::fs::write(&path, program).expect("the README program, written beside the other examples");
    // Formatted the same way the repository's own files are: `cargo fmt --check` covers `examples/`, so a
    // generated file left unformatted would fail the gate for a reason that is not the README's fault.
    let _ = Command::new(env!("CARGO")).args(["fmt", "--", "--emit", "files"]).current_dir(dir).status();
    path
}

#[test]
fn the_readmes_example_compiles() {
    let source = quick_start();
    let example = write_example(&source);
    let output = Command::new(env!("CARGO"))
        .args(["build", "--example", "readme_quick_start", "--features", "readme-example", "--quiet"])
        .current_dir(env!("CARGO_MANIFEST_DIR"))
        .output()
        .expect("cargo runs");
    // The generated file stays: `cargo build --example readme_quick_start --features readme-example` is
    // the same check run by hand, and it is the fastest way for a reader to see the failing snippet.
    let _ = &example;
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        output.status.success(),
        "the README's quick start does not compile:\n{}",
        stderr.lines().take(40).collect::<Vec<_>>().join("\n")
    );
    // A snippet that compiles but warns is still not the example to copy: a missing field shows as an
    // error, but a wrong shape can warn.
    for forbidden in ["unused variable", "missing field", "unused import"] {
        assert!(
            !stderr.contains(forbidden),
            "the README's quick start warns ({forbidden}):\n{}",
            stderr.lines().take(20).collect::<Vec<_>>().join("\n")
        );
    }
}
